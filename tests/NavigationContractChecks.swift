import Foundation
@main struct NavigationContractChecks {
    static func main() {
        for total in [0, 1, 49, 50, 51, 999, 1000, 1003, 10000] {
            let pages = (0..<ChapterPages.count(total: total)).flatMap { Array(ChapterPages.bounds(total: total, page: $0)) }
            precondition(pages == Array(0..<total), "Every chapter must appear once, including the final partial page")
            precondition(ChapterPages.bounds(total: total, page: -1).lowerBound == 0)
            precondition(ChapterPages.bounds(total: total, page: Int.max).upperBound == total)
        }
        let swipe = LibrarySwipeInteraction()
        precondition(swipe.allowsActivation(at: 0), "A normal tap opens a book")
        swipe.changed(horizontal: 4, vertical: 3)
        precondition(swipe.allowsActivation(at: 0), "Small finger jitter is still a tap")
        swipe.ended(at: 0)
        precondition(swipe.allowsActivation(at: 0), "A tap needs no cooldown")
        swipe.changed(horizontal: -25, vertical: 2)
        precondition(!swipe.allowsActivation(at: 10), "An unfinished drag cannot open a cover")
        precondition(LibrarySwipeInteraction.pageStep(horizontal: -25, vertical: 2) == 0)
        swipe.ended(at: 10)
        precondition(!swipe.allowsActivation(at: 10), "An aborted swipe cannot become a release-time tap")
        precondition(!swipe.allowsActivation(at: 10.1), "Delayed release callbacks are suppressed")
        precondition(swipe.allowsActivation(at: 10.3), "A fresh tap works after a swipe")
        swipe.changed(horizontal: 90, vertical: 1)
        swipe.ended(at: 20)
        precondition(!swipe.allowsActivation(at: 20), "An edge swipe cannot open a cover either")
        precondition(LibrarySwipeInteraction.pageStep(horizontal: -100, vertical: 10) == 1)
        precondition(LibrarySwipeInteraction.pageStep(horizontal: 100, vertical: 10) == -1)
        precondition(LibrarySwipeInteraction.pageStep(horizontal: 20, vertical: 100) == 0)
        precondition(LibrarySwipeInteraction.pageStep(horizontal: 100, vertical: 80) == 0)
        swipe.changed(horizontal: 0, vertical: 20)
        precondition(!swipe.allowsActivation(at: 30), "Vertical scrolling is not a cover tap")
        swipe.ended(at: 30)
        precondition(swipe.allowsActivation(at: 31), "Cancelled drags recover on gesture reset")
        precondition(LibrarySwipeInteraction.isTitleSwipe(horizontal: 2, vertical: -50))
        precondition(LibrarySwipeInteraction.isTitleSwipe(horizontal: 2, vertical: 50))
        precondition(!LibrarySwipeInteraction.isTitleSwipe(horizontal: 50, vertical: 2))
        precondition(!LibrarySwipeInteraction.isTitleSwipe(horizontal: 2, vertical: 15))
        precondition(!LibrarySwipeInteraction.isTitleSwipe(horizontal: 40, vertical: 50))
        for direction in [-1.0, 1.0] {
            let sourceSwipe = LibrarySwipeInteraction()
            sourceSwipe.changed(horizontal: direction * 30, vertical: 0)
            precondition(!sourceSwipe.allowsActivation(at: 40), "Browse swipes never activate a source, even without a catalogue change")
            sourceSwipe.ended(at: 40)
            precondition(!sourceSwipe.allowsActivation(at: 40.1))
            precondition(sourceSwipe.allowsActivation(at: 40.3))
        }
        precondition(!MinimalPageSwipe.isVertical(horizontal: 40, vertical: 20), "A horizontal drag never pages")
        precondition(MinimalPageSwipe.isVertical(horizontal: 20, vertical: -40))
        precondition(MinimalPageSwipe.commits(translation: -80, predicted: -90), "An upward drag past the threshold pages")
        precondition(MinimalPageSwipe.commits(translation: -20, predicted: -220), "A flick commits below the drag threshold")
        precondition(!MinimalPageSwipe.commits(translation: -20, predicted: -25), "A short drag springs back")
        precondition(!MinimalPageSwipe.commits(translation: 200, predicted: 300), "A downward drag never pages")
        precondition(!MinimalPageSwipe.commits(translation: 80, predicted: -20), "A drag that ends downward does not page")
        precondition(MinimalPageSwipe.lift(translation: 100) == 0, "A downward drag lifts nothing")
        precondition(MinimalPageSwipe.lift(translation: -12) > 0, "An upward drag lifts at once")
        precondition(MinimalPageSwipe.lift(translation: -100) > MinimalPageSwipe.lift(translation: -12),
                     "The lift keeps growing with the finger")
        precondition(MinimalPageSwipe.lift(translation: -200) > MinimalPageSwipe.lift(translation: -100),
                     "The lift never stops growing, it only slows")
        precondition(MinimalPageSwipe.lift(translation: -5000) < MinimalPageSwipe.maxLift,
                     "The lift approaches its ceiling without reaching it")
        precondition(MinimalPageSwipe.lift(translation: -MinimalPageSwipe.commitDistance) < MinimalPageSwipe.maxLift,
                     "A committing drag is a lift, not a page of travel")
        precondition(SheetDragDecision.resolve(translation: 100, predicted: 110, canDismiss: true) == .dismiss)
        precondition(SheetDragDecision.resolve(translation: 30, predicted: 220, canDismiss: true) == .dismiss)
        precondition(SheetDragDecision.resolve(translation: 100, predicted: 220, canDismiss: false) == .restore)
        precondition(SheetDragDecision.resolve(translation: 10, predicted: 220, canDismiss: true) == .restore)
        precondition(SheetDragDecision.resolve(translation: -60, predicted: -100, canDismiss: true) == .expand)
        precondition(SheetDragDecision.resolve(translation: 20, predicted: 25, canDismiss: true) == .restore)
        var pull = PullToRefreshState()
        pull.changed(distance: 120)
        precondition(!pull.isPulling && !pull.end(distance: 120, enabled: true), "Layout and programmatic scrolls cannot refresh")
        pull.begin(enabled: true)
        pull.changed(distance: 40)
        precondition(pull.isPulling && pull.progress == 0.5 && !pull.didRelease, "Pull progress follows the finger, not an async refresh task")
        pull.changed(distance: 120)
        precondition(pull.progress == 1 && !pull.didRelease, "Crossing the threshold must wait for release")
        precondition(!pull.end(distance: 30, enabled: true), "Pulling back below the threshold cancels the refresh")
        pull.begin(enabled: true)
        precondition(pull.end(distance: 80, enabled: true), "A full pull triggers on release")
        precondition(!pull.end(distance: 90, enabled: true), "One gesture cannot trigger twice")
        pull.changed(distance: 0)
        precondition(pull.distance == 0, "The indicator retracts with bounce, not update completion")
        pull.begin(enabled: false)
        precondition(!pull.end(distance: 120, enabled: true), "A gesture begun during an update stays disabled")
        pull.begin(enabled: true)
        precondition(!pull.end(distance: 120, enabled: false), "Do not start a second update if one began mid-pull")
        pull.begin(enabled: true)
        pull.changed(distance: 120)
        pull.cancel()
        precondition(!pull.end(distance: 120, enabled: true) && pull.distance == 0, "Cancelled touches cannot refresh")
        print("PASS: chapter pages, title gestures, tap suppression, minimal page swipes, sheet drags and pull-to-refresh lifecycle")
    }
}
